# On-Call Rotation Guide

## Schedule

On-call rotations run weekly, Monday to Monday, and are managed through PagerDuty. Each engineer is on-call approximately once every 6 weeks depending on team size.

## Responsibilities

The on-call engineer is the first responder for all production alerts during their rotation. This includes acknowledging pages within 5 minutes and following the incident response runbook for any confirmed incidents.

## Handoff

At the end of each rotation, the outgoing on-call engineer writes a handoff summary covering any ongoing issues, recent incidents, and anything the next engineer should watch for. Handoffs are posted in the #oncall-handoff Slack channel.

## Compensation

Engineers on-call outside of business hours receive on-call pay as outlined in their compensation package. Time spent actively responding to an incident outside business hours can be claimed as overtime.